import { beforeEach, describe, expect, it, vi } from 'vitest'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import type { Challenge, ChallengeStatus, Word } from '../../shared/model'
import { api } from '../lib/api'
import { ChallengePractice } from './ChallengePractice'

const word: Word = { id: '11111111-1111-4111-8111-111111111111', text: 'Schmetterling', language: 'de', category: 'new', consecutive_mistakes: 0, created_at: '2026-10-22T12:00:00Z', last_practiced_at: null }
const challenge: Challenge = { id: '22222222-2222-4222-8222-222222222222', startedAt: '2026-10-22T12:00:00Z', writtenAt: null, reviewedAt: null, nextIndex: 0, words: [{ id: word.id, text: word.text, language: word.language, attemptId: '33333333-3333-4333-8333-333333333333' }], recognition: null, results: null, telemetry: [], check: null, photo: null }
const written: Challenge = { ...challenge, nextIndex: 1, writtenAt: '2026-10-22T12:01:00Z' }
const status: ChallengeStatus = { challenges: [], ocr: { enabled: false, month: '2026-10', used: 0, limit: 450 } }
beforeEach(() => {
  vi.stubGlobal('speechSynthesis', { getVoices: () => [], cancel: vi.fn(), speak: vi.fn() })
  vi.stubGlobal('SpeechSynthesisUtterance', class { text: string; constructor(text: string) { this.text = text } })
  vi.stubGlobal('URL', class extends URL {
    static createObjectURL = vi.fn(() => 'blob:test-photo')
    static revokeObjectURL = vi.fn()
  })
  vi.spyOn(api, 'challengeStatus').mockResolvedValue(status)
})
describe('persisted whole-challenge practice', () => {
  it('keeps setup quiet and waits for an explicit start after the instructions', async () => {
    const user = userEvent.setup()
    const create = vi.spyOn(api, 'createChallenge').mockResolvedValue(challenge)
    render(<ChallengePractice words={[word]} onUpdated={vi.fn()} filters={<label>Language<select defaultValue="de"><option value="de">Deutsch</option></select></label>} />)
    expect(screen.getByRole('combobox', { name: 'Language' })).toBeVisible()
    expect(screen.queryByRole('spinbutton', { name: 'Seconds between words' })).not.toBeInTheDocument()
    expect(screen.queryByRole('checkbox', { name: 'Automatic dictation' })).not.toBeInTheDocument()
    expect(screen.queryByText('Instructions & photo info')).not.toBeInTheDocument()
    expect(screen.queryByText(/Get a pen and paper/)).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Start 10 words' })).toHaveClass('secondary')
    expect(screen.getByRole('button', { name: 'Start 15 words' })).toHaveClass('primary')
    expect(screen.getByRole('button', { name: 'Start 20 words' })).toHaveClass('secondary')
    await user.click(await screen.findByRole('button', { name: 'Start 10 words' }))
    expect(screen.getByRole('heading', { name: 'Ready to write?' })).toBeVisible()
    expect(screen.getByText('Get a pen and paper. Write your answers in order.')).toBeVisible()
    expect(screen.getByText('Listen and write each word. Use the controls to pause or change speed.')).toBeVisible()
    expect(screen.queryByText(/Number your answers/)).not.toBeInTheDocument()
    expect(screen.getByText('1 word')).toBeVisible()
    expect(create).not.toHaveBeenCalled()
    expect(window.speechSynthesis.speak).not.toHaveBeenCalled()
    expect(screen.queryByRole('button', { name: 'Cancel' })).not.toBeInTheDocument()
    expect(within(screen.getByRole('region', { name: 'Practice challenges' })).getAllByRole('button')).toHaveLength(1)
    await user.click(screen.getByRole('button', { name: 'Start' }))
    expect(create).toHaveBeenCalledWith([word.id])
    expect(screen.getByRole('heading', { name: 'Write answer number 1.' })).toBeVisible()
    expect(document.body).not.toHaveTextContent(word.text)
  })

  it('keeps statistics out of the learning path while keeping pending checks available', async () => {
    const reviewed: Challenge = { ...written, id: '44444444-4444-4444-8444-444444444444', reviewedAt: '2026-10-22T12:02:00Z', results: [true], check: { method: 'manual', spellings: [word.text], evaluatedAt: '2026-10-22T12:02:00Z' } }
    vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [written, reviewed] })
    const { rerender } = render(<ChallengePractice words={[word]} onUpdated={vi.fn()} />)
    expect(await screen.findByRole('button', { name: 'Manual check' })).toBeVisible()
    expect(screen.queryByRole('region', { name: 'Challenge statistics' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'View results' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Remove challenge' })).toBeVisible()
    rerender(<ChallengePractice view="statistics" words={[word]} onUpdated={vi.fn()} />)
    expect(screen.getByRole('region', { name: 'Challenge statistics' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'View results' })).toBeVisible()
    rerender(<ChallengePractice words={[word]} onUpdated={vi.fn()} />)
    expect(screen.queryByRole('region', { name: 'Challenge statistics' })).not.toBeInTheDocument()
  })

  it('conceals spelling while writing, persists position, and only saves after a complete manual parent review', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'createChallenge').mockResolvedValue(challenge)
    const advance = vi.spyOn(api, 'advanceChallenge').mockResolvedValue(written)
    const review = vi.spyOn(api, 'reviewChallenge').mockResolvedValue({ ...written, reviewedAt: '2026-10-22T12:02:00Z', results: [true], check: { method: 'manual', spellings: [word.text], evaluatedAt: '2026-10-22T12:02:00Z' } })
    const refresh = vi.fn().mockResolvedValue(undefined)
    render(<ChallengePractice words={[word]} onUpdated={refresh} />)
    await user.click(await screen.findByRole('button', { name: 'Start 10 words' }))
    await user.click(screen.getByRole('button', { name: 'Start' }))
    expect(document.body).not.toHaveTextContent(word.text)
    expect(screen.queryByText(/expected spelling/i)).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Finish challenge' }))
    expect(advance).toHaveBeenCalledWith(challenge.id, 1, expect.objectContaining({ action: 'next', automatic: false }))
    expect(document.body).not.toHaveTextContent(word.text)
    await user.click(screen.getByRole('button', { name: 'Manual check' }))
    expect(screen.getByText(word.text)).toBeInTheDocument()
    expect(review).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: /confirm all/i })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Correct' }))
    await user.click(screen.getByRole('button', { name: /confirm all/i }))
    expect(review).toHaveBeenCalledWith(challenge.id, [true], { method: 'manual', spellings: [word.text] })
    expect(await screen.findByRole('status')).toHaveTextContent('Results saved.')
    expect(screen.getByText(/Check evaluated/)).not.toBeVisible()
    expect(screen.queryByRole('region', { name: 'Challenge statistics' })).not.toBeInTheDocument()
    await user.click(screen.getByText('Challenge details', { selector: 'summary' }))
    expect(screen.getByText(/Check evaluated/)).toBeVisible()
    expect(refresh).toHaveBeenCalledOnce()
  })
  it('resumes the saved numbered position without setup instructions or photo configuration', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [challenge] })
    render(<ChallengePractice words={[]} onUpdated={vi.fn()} />)
    expect(screen.queryByText('Instructions & photo info')).not.toBeInTheDocument()
    await user.click(await screen.findByRole('button', { name: 'Continue challenge' }))
    expect(document.body).not.toHaveTextContent(word.text)
    expect(screen.getByRole('heading', { name: /write answer number 1/i })).toBeInTheDocument()
  })
  it.each([{ name: 'unfinished', saved: challenge }, { name: 'awaiting checking', saved: written }])('confirms deletion of an $name challenge from Continue learning', async ({ saved }) => {
    const user = userEvent.setup()
    const load = vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [saved] })
    const remove = vi.spyOn(api, 'deleteChallenge').mockResolvedValue(undefined)
    render(<ChallengePractice words={[]} onUpdated={vi.fn()} />)
    const trash = await screen.findByRole('button', { name: 'Remove challenge' })
    expect(trash).toHaveAttribute('title', 'Remove challenge')
    if (!saved.writtenAt) {
      const play = screen.getByRole('button', { name: 'Continue challenge' })
      expect(play).toHaveAttribute('title', 'Continue challenge')
      expect(play.textContent).toBe('')
      expect(play.querySelector('svg')).toBeInTheDocument()
    }
    await user.click(trash)
    expect(screen.getByText('Remove this challenge and its statistics? Word progress stays.')).toBeVisible()
    expect(remove).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Cancel' }))
    expect(screen.queryByRole('button', { name: 'Confirm removal' })).not.toBeInTheDocument()
    expect(remove).not.toHaveBeenCalled()
    await user.click(trash)
    load.mockResolvedValue(status)
    await user.click(screen.getByRole('button', { name: 'Confirm removal' }))
    expect(remove).toHaveBeenCalledExactlyOnceWith(saved.id)
    await waitFor(() => expect(screen.queryByText('Continue learning')).not.toBeInTheDocument())
    expect(screen.queryByRole('button', { name: 'Remove challenge' })).not.toBeInTheDocument()
  })
  it('keeps a challenge available when deletion fails', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [challenge] })
    vi.spyOn(api, 'deleteChallenge').mockRejectedValue(new Error('Connection lost'))
    render(<ChallengePractice words={[]} onUpdated={vi.fn()} />)
    await user.click(await screen.findByRole('button', { name: 'Remove challenge' }))
    await user.click(screen.getByRole('button', { name: 'Confirm removal' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Connection lost')
    expect(screen.getByRole('button', { name: 'Continue challenge' })).toBeEnabled()
    expect(screen.getByRole('button', { name: 'Confirm removal' })).toBeEnabled()
  })
  it('uploads only after explicit consent, keeps uncertain suggestions unmarked, and supports a retry without changing the submitted batch', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [written], ocr: { ...status.ocr, enabled: true } })
    const read = vi.spyOn(api, 'readPhoto').mockResolvedValue({ ...written, recognition: { answers: [{ number: 1, text: 'Schmeterling', confidence: 0.6 }], warnings: ['Check this answer.'] } })
    const review = vi.spyOn(api, 'reviewChallenge').mockRejectedValueOnce(new Error('Connection lost')).mockResolvedValueOnce({ ...written, results: [false], reviewedAt: '2026-10-22T12:02:00Z', check: { method: 'photo', spellings: ['Schmeterling'], evaluatedAt: '2026-10-22T12:02:00Z' } })
    render(<ChallengePractice words={[]} onUpdated={vi.fn()} />)
    await user.click(await screen.findByRole('button', { name: 'Auto check' }))
    const file = new File(['test-photo'], 'answers.png', { type: 'image/png' })
    await user.upload(screen.getByLabelText(/one photo of your answers/i), file)
    expect(read).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: /send photo to azure/i }))
    expect(read).toHaveBeenCalledWith(challenge.id, file)
    expect(within(screen.getByRole('list', { name: 'Your answers' })).getByText('Schmeterling')).toBeVisible()
    expect(screen.getByText('Uncertain reading')).toBeVisible()
    expect(screen.getByText(/Recognition confidence: 60%/)).not.toBeVisible()
    expect(screen.getByRole('button', { name: /confirm all/i })).toBeDisabled()
    expect(review).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Incorrect' }))
    await user.click(screen.getByRole('button', { name: /confirm all/i }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Connection lost')
    expect(screen.getByLabelText('Written spelling (optional)')).toBeDisabled()
    await user.click(screen.getByRole('button', { name: /retry confirming/i }))
    const details = { method: 'photo', spellings: ['Schmeterling'] }
    expect(review.mock.calls).toEqual([[challenge.id, [false], details], [challenge.id, [false], details]])
  })

  it('shows reviewed statistics and exact historical word results without recording another attempt', async () => {
    const user = userEvent.setup()
    const reviewed: Challenge = { ...written, reviewedAt: '2026-10-22T12:02:00Z', results: [false], check: { method: 'manual', spellings: [null], evaluatedAt: '2026-10-22T12:02:00Z' } }
    vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [{ ...challenge, id: '44444444-4444-4444-8444-444444444444' }, reviewed] })
    const review = vi.spyOn(api, 'reviewChallenge')
    render(<ChallengePractice view="statistics" words={[]} onUpdated={vi.fn()} />)
    const stats = await screen.findByRole('region', { name: 'Challenge statistics' })
    expect(stats).toHaveTextContent('1 / 2')
    expect(stats).toHaveTextContent('1Incorrect answers')
    expect(stats).toHaveTextContent('0%')
    expect(stats).toHaveTextContent('1 unfinished challenge · 1 unmarked word')
    await user.click(screen.getByRole('button', { name: 'View results' }))
    expect(screen.getByText(word.text)).toBeInTheDocument()
    expect(screen.getByText('Keep practicing')).toBeInTheDocument()
    expect(review).not.toHaveBeenCalled()
  })

  it('does not count OCR suggestions or unfinished challenges as incorrect answers', async () => {
    vi.spyOn(api, 'challengeStatus').mockResolvedValue({ ...status, challenges: [{ ...written, recognition: { answers: [{ number: 1, text: 'wrong', confidence: 0.99 }], warnings: [] } }] })
    render(<ChallengePractice view="statistics" words={[]} onUpdated={vi.fn()} />)
    const stats = await screen.findByRole('region', { name: 'Challenge statistics' })
    expect(stats).toHaveTextContent('0Correct answers')
    expect(stats).toHaveTextContent('0Incorrect answers')
    expect(stats).toHaveTextContent('—Accuracy')
    expect(within(stats).queryByRole('img')).not.toBeInTheDocument()
  })
})
