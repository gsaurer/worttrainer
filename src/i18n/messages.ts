export function translateError(language: WebsiteLanguage, text: string): string {
  if (language === 'en') return text
  if (Object.hasOwn(german, text)) return translate(language, text as Message)
  if (Object.hasOwn(germanErrors, text)) return germanErrors[text]
  const duplicate = /^Number (\d+) appeared more than once\. Mark it yourself\.$/.exec(text)
  if (duplicate) return translate(language, 'Number {number} appeared more than once. Mark it yourself.', { number: duplicate[1] })
  if (/^(Invalid (input|option|UUID)|Too (small|big):|Unrecognized key)/.test(text)) return 'Prüfe deine Eingaben und versuche es erneut.'
  return text
}
